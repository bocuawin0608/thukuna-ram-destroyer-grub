#!/usr/bin/env bash
# ==============================================================================
# INFERNAL — Isolated Test Sandbox Helper (tests/test-helpers.sh)
# ==============================================================================
# Builds disposable mock filesystems and mock binaries in temporary directories
# so all detection, installation, rollback, and idempotency tests run with zero
# risk to the host machine. Uses real /usr/bin/grub-script-check for validation.
# ==============================================================================

set -euo pipefail

TESTS_Passed=0
TESTS_Failed=0

pass_test() {
    local name="$1"
    TESTS_Passed=$((TESTS_Passed + 1))
    printf '  [PASS] %s\n' "${name}"
}

fail_test() {
    local name="$1"
    local reason="${2:-}"
    TESTS_Failed=$((TESTS_Failed + 1))
    printf '  [FAIL] %s — %s\n' "${name}" "${reason}" >&2
}

assert_contains() {
    local haystack="$1"
    local needle="$2"
    local test_name="$3"
    if [[ "${haystack}" == *"${needle}"* ]]; then
        pass_test "${test_name}"
    else
        fail_test "${test_name}" "Expected output to contain '${needle}'"
    fi
}

assert_eq() {
    local actual="$1"
    local expected="$2"
    local test_name="$3"
    if [[ "${actual}" == "${expected}" ]]; then
        pass_test "${test_name}"
    else
        fail_test "${test_name}" "Expected '${expected}', got '${actual}'"
    fi
}

create_mock_sandbox() {
    local sb
    sb="$(mktemp -d)"
    mkdir -p "${sb}/root/etc/default" \
             "${sb}/root/etc/grub.d" \
             "${sb}/root/var/backups/infernal-grub-theme" \
             "${sb}/bin"
    printf '%s\n' "${sb}"
}

setup_mock_binaries() {
    local bin_dir="$1"
    local pkg_mgr="${2:-pacman}"
    local grub_cmd="${3:-grub-mkconfig}"
    local grub_ver="${4:-grub-mkconfig (GRUB) 2:2.16-1}"
    local include_optional="${5:-true}"

    # Package manager stub
    cat > "${bin_dir}/${pkg_mgr}" <<'EOF'
#!/usr/bin/env bash
echo "mock package manager invoked: $*"
EOF
    chmod +x "${bin_dir}/${pkg_mgr}"

    # grub-mkconfig / grub2-mkconfig stub that reads ${INFERNAL_ROOT}/etc/default/grub
    # and generates a realistic grub.cfg preserving existing menuentries + setting theme
    if [[ "${grub_cmd}" != "none" ]]; then
        cat > "${bin_dir}/${grub_cmd}" <<EOF
#!/usr/bin/env bash
set -euo pipefail
if [[ "\${1:-}" == "--version" ]]; then
    echo "${grub_ver}"
    exit 0
fi
out_file=""
while [[ \$# -gt 0 ]]; do
    case "\$1" in
        -o) out_file="\$2"; shift 2 ;;
        *) shift ;;
    esac
done
[[ -z "\${out_file}" ]] && exit 1

root_dir="\${INFERNAL_ROOT:-/}"
def_file="\${root_dir%/}/etc/default/grub"
theme_val=""
def_val="0"
timeout_val="5"
if [[ -f "\${def_file}" ]]; then
    theme_val="\$(sed -n 's/^[[:space:]]*GRUB_THEME="\\{0,1\\}\\([^"]*\\)"\\{0,1\\}\$/\\1/p' "\${def_file}" | tail -n 1)"
    def_val="\$(sed -n 's/^[[:space:]]*GRUB_DEFAULT="\\{0,1\\}\\([^"]*\\)"\\{0,1\\}\$/\\1/p' "\${def_file}" | tail -n 1)"
    timeout_val="\$(sed -n 's/^[[:space:]]*GRUB_TIMEOUT="\\{0,1\\}\\([^"]*\\)"\\{0,1\\}\$/\\1/p' "\${def_file}" | tail -n 1)"
fi

cat > "\${out_file}" <<CFG
#
# DO NOT EDIT THIS FILE
# Generated by ${grub_cmd}
#
set default="\${def_val:-0}"
set timeout=\${timeout_val:-5}
CFG

if [[ -n "\${theme_val}" ]]; then
    cat >> "\${out_file}" <<CFG
insmod gfxterm
insmod png
loadfont (\\\$root)/boot/grub/themes/infernal/fonts/infernal_serif_regular_16.pf2
loadfont (\\\$root)/boot/grub/themes/infernal/fonts/infernal_serif_bold_18.pf2
set theme=(\\\$root)\${theme_val}
export theme
CFG
fi

# Preserve existing menuentries from current grub.cfg if present
orig_cfg="\${root_dir%/}/boot/grub/grub.cfg"
[[ ! -f "\${orig_cfg}" && -f "\${root_dir%/}/boot/grub2/grub.cfg" ]] && orig_cfg="\${root_dir%/}/boot/grub2/grub.cfg"
if [[ -f "\${orig_cfg}" ]]; then
    awk '/^menuentry /,/^\}/' "\${orig_cfg}" >> "\${out_file}"
fi
EOF
        chmod +x "${bin_dir}/${grub_cmd}"
    fi

    # Link real grub-script-check and grub-mkfont if available
    if command -v grub-script-check >/dev/null 2>&1; then
        ln -sf "$(command -v grub-script-check)" "${bin_dir}/grub-script-check"
    fi
    if command -v grub-mkfont >/dev/null 2>&1; then
        ln -sf "$(command -v grub-mkfont)" "${bin_dir}/grub-mkfont"
    fi

    if [[ "${include_optional}" == "true" ]]; then
        cat > "${bin_dir}/os-prober" <<'EOF'
#!/usr/bin/env bash
echo "/dev/nvme0n1p1@/EFI/Microsoft/Boot/bootmgfw.efi:Windows Boot Manager:Windows:efi"
echo "/dev/nvme0n1p4:Ubuntu 24.04.1 LTS (24.04):Ubuntu:linux"
EOF
        chmod +x "${bin_dir}/os-prober"

        cat > "${bin_dir}/efibootmgr" <<'EOF'
#!/usr/bin/env bash
echo "BootCurrent: 0001"
echo "BootOrder: 0001,0000,0002"
echo "Boot0000* Windows Boot Manager	HD(1,GPT,1111)/File(\EFI\Microsoft\Boot\bootmgfw.efi)"
echo "Boot0001* endeavouros	HD(1,GPT,1111)/File(\EFI\endeavouros\grubx64.efi)"
echo "Boot0002* Fedora	HD(1,GPT,1111)/File(\EFI\fedora\shimx64.efi)"
EOF
        chmod +x "${bin_dir}/efibootmgr"
    fi
}

populate_distro_fixture() {
    local root_dir="$1"
    local distro_id="$2"
    local distro_like="$3"
    local pretty_name="$4"
    local boot_mode="${5:-uefi}"
    local grub_subdir="${6:-grub}"

    cat > "${root_dir}/etc/os-release" <<EOF
NAME="${pretty_name}"
ID=${distro_id}
ID_LIKE=${distro_like}
PRETTY_NAME="${pretty_name}"
EOF

    if [[ "${boot_mode}" == "uefi" ]]; then
        mkdir -p "${root_dir}/sys/firmware/efi/efivars" \
                 "${root_dir}/boot/efi/EFI/Microsoft/Boot" \
                 "${root_dir}/boot/efi/EFI/${distro_id}"
        touch "${root_dir}/boot/efi/EFI/Microsoft/Boot/bootmgfw.efi"
        # SecureBoot disabled (0x00 at byte 5)
        printf '\x06\x00\x00\x00\x00' > "${root_dir}/sys/firmware/efi/efivars/SecureBoot-8be4df61-93ca-11d2-aa0d-00e098032b8c"
    fi

    mkdir -p "${root_dir}/boot/${grub_subdir}/themes"

    cat > "${root_dir}/etc/default/grub" <<'EOF'
# GRUB boot loader configuration
GRUB_DEFAULT="saved"
GRUB_TIMEOUT=5
GRUB_DISTRIBUTOR="Linux"
GRUB_CMDLINE_LINUX_DEFAULT="quiet splash loglevel=3"
GRUB_CMDLINE_LINUX=""
GRUB_DISABLE_OS_PROBER=false
EOF

    cat > "${root_dir}/etc/grub.d/40_custom" <<'EOF'
#!/bin/sh
exec tail -n +3 $0
menuentry 'System Rescue Live ISO (Custom)' --class recovery {
    insmod gzio
    linux /boot/vmlinuz-rescue
}
EOF

    cat > "${root_dir}/boot/${grub_subdir}/grub.cfg" <<'EOF'
set default="saved"
set timeout=5
menuentry 'EndeavourOS Linux, with Linux 6.18.2-arch2-1' --class endeavouros --class gnu-linux {
    insmod gzio
    linux /boot/vmlinuz-linux root=UUID=1111-2222 rw quiet
    initrd /boot/initramfs-linux.img
}
menuentry 'Windows Boot Manager (on /dev/nvme0n1p1)' --class windows --class os {
    insmod part_gpt
    insmod fat
    chainloader /EFI/Microsoft/Boot/bootmgfw.efi
}
menuentry 'Arch Linux (on /dev/nvme0n1p3)' --class arch --class gnu-linux {
    linux /boot/vmlinuz-linux root=/dev/nvme0n1p3 rw
}
menuentry 'Ubuntu 24.04 LTS (on /dev/nvme0n1p4)' --class ubuntu --class gnu-linux {
    linux /boot/vmlinuz root=/dev/nvme0n1p4 ro quiet splash
}
menuentry 'UEFI Firmware Settings' $menuentry_id_option 'uefi-firmware' {
    fwsetup
}
EOF
}
